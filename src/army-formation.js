import { CONFIG } from "./config.js";

/** Construct an army; deployment and mountain health are explicit spawn policies. */
export function createArmyFormation(
	{
		id = Math.random(),
		lat,
		lng,
		sideIndex,
		sovereignId,
		isAlpenjager = false,
		mountainHealth = false,
		deployTicks = 30,
		...fields
	},
	config = CONFIG,
) {
	const formation = {
		id,
		kind: "army",
		lat,
		lng,
		sideIndex,
		sovereignId,
		beneficiaryId: sovereignId,
		isAlpenjager,
		health:
			config.UNIT_HEALTH *
			(mountainHealth && isAlpenjager ? config.ALPEN_HEALTH_MULT : 1),
		lastAttack: 0,
		deployTicks,
		// Every field the simulation adds later, declared up front so formations
		// share one V8 hidden class. Mixed shapes made unit property reads
		// megamorphic in every hot loop. undefined matches an absent field.
		maxHealth: undefined,
		personnel: undefined,
		personnelCapacity: undefined,
		nominalPersonnel: undefined,
		strengthMultiplier: undefined,
		_liveGeneration: undefined,
		_tickAllyWeight: undefined,
		_tickLocalAllyCount: undefined,
		_tickHasNearbyHostile: undefined,
		repulsionVector: undefined,
		_isAtSea: undefined,
		_mopUpAssignedCountryId: undefined,
		_armyNavalReserve: undefined,
		_armyOrder: undefined,
		_armySectorId: undefined,
		_taskForceUid: undefined,
		_taskForceRole: undefined,
		_taskForceOrder: undefined,
		dirLat: undefined,
		dirLng: undefined,
		isAtSea: undefined,
		mountainIntensity: undefined,
		lineDefense: 1,
		encircledTicks: undefined,
		_cachedTarget: undefined,
		_cachedScanKx: undefined,
		_cachedScanKy: undefined,
		_cachedLocalEnemyCount: undefined,
		_cachedEnemyCentroidLat: undefined,
		_cachedEnemyCentroidLng: undefined,
		_lastFullScanTick: undefined,
		lastAllyCount: undefined,
		mopUpTarget: undefined,
		mopUpTargetId: undefined,
		lastMopUpId: undefined,
		targetSearchCooldown: undefined,
		_cityObjective: undefined,
		_cityObjectiveTick: undefined,
		_strategicTargetGeneration: undefined,
		_strategicBeneficiaryId: undefined,
		navalAssigned: undefined,
		isTransport: undefined,
		_neutralCheckLat: undefined,
		_neutralCheckLng: undefined,
		_neutralDirLat: undefined,
		_neutralDirLng: undefined,
		_neutralBlocked: undefined,
		_coastStuckTicks: undefined,
		frontSlot: undefined,
		_armyRecovering: undefined,
		_armyNavigation: undefined,
		_armyLastNavStatus: undefined,
		_armyMoveStatus: undefined,
		lastCombatTick: undefined,
		_transportPlanSignature: undefined,
		_assignedPlanSignature: undefined,
		_planWaypointSignature: undefined,
		_planWaypointIndex: undefined,
		victoryBoostTicks: undefined,
		_armyRecoveryTick: undefined,
		_supplyCollapsedTick: undefined,
		coastalAssigned: undefined,
		supplyAssigned: undefined,
		garrisonAssigned: undefined,
		_armyExhaustedHealth: undefined,
		_armyLastReinforceTick: undefined,
		_defenderReactTarget: undefined,
		_landedAt: undefined,
		_mopUpModeActive: undefined,
	};
	return Object.assign(formation, fields);
}
