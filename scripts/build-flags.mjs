// Download the flag images the game uses into assets/flags/ and write the
// manifest src/flag-manifest.js. Run after changing assets/geodata/flagcodes.json
// or when a built-in scenario references a new remote flag.
//   node scripts/build-flags.mjs
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { gunzipSync } from "node:zlib";
import { decodeScenarioBinary } from "../src/scenario-codec.js";

const root = new URL("../", import.meta.url);
const flagDir = new URL("assets/flags/", root);
const legacyDir = new URL("assets/flags/legacy/", root);
mkdirSync(legacyDir, { recursive: true });

async function download(url, target) {
	const response = await fetch(url);
	if (!response.ok) throw new Error(`${url}: HTTP ${response.status}`);
	writeFileSync(target, new Uint8Array(await response.arrayBuffer()));
}

async function inBatches(items, size, task) {
	for (let i = 0; i < items.length; i += size)
		await Promise.all(items.slice(i, i + size).map(task));
}

// Country and subdivision flags from flagcdn.com (public domain per Flagpedia).
const codes = Object.keys(
	JSON.parse(readFileSync(new URL("assets/geodata/flagcodes.json", root))),
)
	.map((code) => code.toLowerCase())
	.sort();
await inBatches(codes, 16, (code) =>
	download(
		`https://flagcdn.com/w320/${code}.webp`,
		new URL(`${code}.webp`, flagDir),
	),
);

// Custom flags the built-in scenarios used to load from WebSim's blob store.
const legacy = new Set();
for (const name of [
	"world-map-2026-v3",
	"ukraine-2023-v3",
	"world-map-2022-v3",
]) {
	const bytes = gunzipSync(
		readFileSync(new URL(`assets/maps/compiled/${name}.mwsc.gz`, root)),
	);
	for (const meta of decodeScenarioBinary(bytes).scenario.metadata ?? []) {
		for (const [key, value] of Object.entries(meta ?? {}))
			if (/flagUrl$/i.test(key) && typeof value === "string") {
				const match = value.match(
					/^https:\/\/api\.websim\.com\/blobs\/([\w-]+\.(?:png|webp|gif|svg))$/,
				);
				if (match) legacy.add(match[1]);
			}
	}
}
const legacyFiles = [...legacy].sort();
await inBatches(legacyFiles, 8, (file) =>
	download(`https://api.websim.com/blobs/${file}`, new URL(file, legacyDir)),
);

writeFileSync(
	new URL("src/flag-manifest.js", root),
	`// Generated by scripts/build-flags.mjs. Do not edit by hand.
export const BUNDLED_FLAG_CODES = ${JSON.stringify(codes)};
export const LEGACY_FLAG_FILES = ${JSON.stringify(legacyFiles)};
`,
);
console.log(`${codes.length} flags, ${legacyFiles.length} legacy flags`);
