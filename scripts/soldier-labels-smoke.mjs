const midpoint = label => ({ x: (label.curve[0].x + 3 * label.curve[1].x + 3 * label.curve[2].x + label.curve[3].x) / 8, y: (label.curve[0].y + 3 * label.curve[1].y + 3 * label.curve[2].y + label.curve[3].y) / 8 });
for (const frontKey of Object.keys(frame.frontlines)) {
	const friendly = layout.find(g => g.frontKey === frontKey && g.countryId === 1);
	const enemy = layout.find(g => g.frontKey === frontKey && g.countryId === 3);
	assert.ok(midpoint(friendly).x < midpoint(enemy).x, "opposing countries place their totals on their respective side of a vertical front");
}
const drawn = drawSoldierFrontLabels(drawingFrame);
assert.equal(drawn.length, 5);
assert.ok(drawing.trace.filter(([key]) => key === "rotate").some(([, angle]) => Math.abs(angle) > 0.5), "soldier numbers follow steep fronts rather than always hovering horizontally");
assert.ok(drawing.trace.some(([key, text]) => key === "fillText" && text === "FRA"), "country identity remains visible before its flag loads");
assert.ok(drawing.trace.every(([key, ...args]) => !["translate", "rotate"].includes(key) || args.every(Number.isFinite)));
