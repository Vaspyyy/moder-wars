// Compare the spatial search to an exhaustive nearest-front oracle, including
// polar distortion, bucket edges and the longitude seam.
let seed = 91823;
const random = () => ((seed = Math.imul(seed, 1664525) + 1013904223 >>> 0) / 2 ** 32);
const wrapLng = lng => ((lng + 180) % 360 + 360) % 360 - 180;
for (let trial = 0; trial < 180; trial++) {
	const lat = random() * 178 - 89, lng = random() * 360 - 180;
	const frontlines = {};
	for (let i = 0; i < 12; i++) frontlines[`0_1_${i}`] = [{ lat: Math.max(-89, Math.min(89, lat + random() * 16 - 8)), lng: wrapLng(lng + random() * 48 - 24) }];
	let expected = null, best = 36;
	const scale = Math.max(0.25, Math.cos(lat * Math.PI / 180));
	for (const [key, [point]] of Object.entries(frontlines)) {
		const distance = (lat - point.lat) ** 2 + (wrapLng(lng - point.lng) * scale) ** 2;
		if (distance < best) { best = distance; expected = key; }
	}
	const actual = collectSoldierFrontGroups({ ...frame, frontlines, units: [unit(20, 0, 1, lng, 1000, { lat })] });
	assert.equal(actual[0].frontKey, expected, "indexed search must agree with exhaustive nearest-front assignment");
}

function drawFixture() {
	const trace = [], stack = [];
	const ctx = new Proxy({ font: "", measureText(text) { return { width: text.length * parseFloat(this.font.match(/([\d.]+)px/)?.[1] || 12) * 0.55 }; } }, {
		get(target, key) {
			if (key in target) return target[key];
			if (key === "save") return () => { stack.push({ font: target.font }); };
			if (key === "restore") return () => { Object.assign(target, stack.pop()); };
			return (...args) => trace.push([key, ...args]);
		},
	});
	return { ctx, trace, map: { getZoom: () => 6, getSize: () => ({ x: 1000, y: 650 }) }, project: (lat, lng) => ({ x: 500 + lng * 70, y: 330 - (lat - 54.25) * 70 }) };
}
