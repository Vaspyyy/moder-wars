// Refresh public aggregate observations explicitly; normal builds use the pinned snapshot.
import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { gunzipSync, gzipSync } from "node:zlib";

const root = new URL("../", import.meta.url);
const directory = new URL("assets/data/forces/", root);
const snapshotPath = new URL("world-bank.json.gz", directory);
const args = process.argv.slice(2);
assert(
	args.every((arg) => ["--refresh", "--check"].includes(arg)),
	"Usage: node scripts/import-force-profiles.mjs [--refresh] [--check]",
);
assert(
	!(args.includes("--refresh") && args.includes("--check")),
	"Refresh and check are separate operations",
);
const endpoints = {
	countries:
		"https://api.worldbank.org/v2/country/all?format=json&per_page=500",
	personnel:
		"https://api.worldbank.org/v2/country/all/indicator/MS.MIL.TOTL.P1?format=json&date=2018:2020&per_page=20000",
	population:
		"https://api.worldbank.org/v2/country/all/indicator/SP.POP.TOTL?format=json&date=2018:2025&per_page=20000",
	gdp: "https://api.worldbank.org/v2/country/all/indicator/NY.GDP.MKTP.CD?format=json&date=2018:2025&per_page=20000",
};
await mkdir(directory, { recursive: true });
let snapshot;
if (args.includes("--refresh")) {
	snapshot = {
		retrievedAt: new Date().toISOString().slice(0, 10),
		endpoints,
		responses: {},
	};
	for (const [key, url] of Object.entries(endpoints)) {
		const response = await fetch(url, { signal: AbortSignal.timeout(60000) });
		assert(response.ok, `${key}: HTTP ${response.status}`);
		const data = await response.json();
		assert(
			Array.isArray(data?.[1]) && data[0].pages === 1,
			`${key}: incomplete API response`,
		);
		snapshot.responses[key] = data;
	}
	await writeFile(
		snapshotPath,
		gzipSync(JSON.stringify(snapshot), { level: 9 }),
	);
} else {
	snapshot = JSON.parse(gunzipSync(await readFile(snapshotPath)));
}
const countries = {};
for (const country of snapshot.responses.countries[1]) {
	if (country.region.id === "NA" || !/^[A-Z]{3}$/.test(country.id)) continue;
	countries[country.id] = {
		iso2: country.iso2Code,
		name: country.name,
		personnel: [],
		population: [],
		gdp: [],
	};
}
for (const key of ["personnel", "population", "gdp"]) {
	for (const row of snapshot.responses[key][1]) {
		const country = countries[row.countryiso3code];
		if (!country || row.value === null) continue;
		assert(
			Number.isFinite(row.value) && row.value >= 0 && /^\d{4}$/.test(row.date),
			`${key}: invalid observation`,
		);
		country[key].push([Number(row.date), row.value]);
	}
	for (const country of Object.values(countries))
		country[key].sort((a, b) => b[0] - a[0]);
}
const data = {
	version: 1,
	retrievedAt: snapshot.retrievedAt,
	sourceDates: Object.fromEntries(
		["personnel", "population", "gdp"].map((key) => [
			key,
			snapshot.responses[key][0].lastupdated || snapshot.retrievedAt,
		]),
	),
	countries,
};
const content = `// Generated by scripts/import-force-profiles.mjs. Source/license details: assets/data/forces/README.md.\n// biome-ignore format: Keep the generated numeric snapshot compact and reproducible.\nexport const COUNTRY_FORCE_DATA = ${JSON.stringify(data)};\n`;
const output = new URL("src/country-force-data.js", root);
if (args.includes("--check"))
	assert.equal(
		await readFile(output, "utf8"),
		content,
		"Bundled observations differ from the pinned source snapshot",
	);
else await writeFile(output, content);
const bytes = await readFile(snapshotPath);
console.log(
	JSON.stringify({
		countries: Object.keys(countries).length,
		personnelCountries: Object.values(countries).filter(
			(c) => c.personnel.length,
		).length,
		snapshotSha256: createHash("sha256").update(bytes).digest("hex"),
		bytes: bytes.length,
		generatedBytes: content.length,
	}),
);
